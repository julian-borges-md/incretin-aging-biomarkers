#!/usr/bin/env python3
"""make_tables.py: write manuscript/TABLES_2_to_7_<date>.md from the pipeline outputs.

The tables of the manuscript are generated, never typed: every cell comes from
analysis/output/*.csv or analysis/data/*.csv produced by the gate chain, so a rerun of the chain
followed by this script reproduces the tables exactly. Table 1 (the biomarker inventory) and Table 6
(normalisation thresholds) are written by hand elsewhere and are referenced, not regenerated.

Usage
  python3 -I src/make_tables.py [YYYY-MM-DD]
"""
import csv, os, sys, statistics, collections
from datetime import date

ROOT = os.getcwd()
OUT = os.path.join(ROOT, "analysis", "output")
DAT = os.path.join(ROOT, "analysis", "data")


def rd(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def num(x, n=1):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return "NA"


def main(stamp):
    t2 = rd(os.path.join(OUT, "table2_pooled_by_biomarker.csv"))
    t3 = rd(os.path.join(OUT, "table3_class_coverage.csv"))
    t3b = rd(os.path.join(OUT, "table3b_class_signature_descriptive.csv"))
    t5 = rd(os.path.join(OUT, "table5_composite.csv"))
    t5b = rd(os.path.join(OUT, "table5b_composite_contributions.csv"))
    sens = rd(os.path.join(OUT, "table2_sensitivity_corr.csv"))
    master = rd(os.path.join(DAT, "extraction_master.csv"))
    rob = rd(os.path.join(DAT, "risk_of_bias.csv"))

    lines = []
    w = lines.append
    w(f"# Tables 2 to 7, generated {stamp}")
    w("")
    w("Generated by `python3 -I src/make_tables.py` from the gate chain outputs; no cell is typed by")
    w("hand. Table 1 (the 36 marker inventory) and Table 6 (normalisation thresholds) live in the")
    w("manuscript and are referenced here rather than regenerated.")
    w("")

    # ---- Table 2
    #
    # Decision C1 of the Director register: Table 2 is the pooled table and holds only pooled
    # quantities. Binary outcomes were appearing in it, and one of them put an interval of minus
    # 807.5 to plus 807.1 per cent on an estimate of minus 0.22 from two trials, which carries no
    # information and invites a reviewer to question everything near it. The other was a single
    # trial reported as a pooled estimate.
    #
    # They are excluded by OUTCOME TYPE, read from the master, rather than by naming the two
    # markers, so a binary outcome added by a later extraction is excluded the day it arrives
    # instead of reappearing here for want of being listed. They are then reported below the table
    # as what they are, event counts per arm, generated from the master like every other cell.
    binary_markers = {(r.get("biomarker") or "").strip() for r in master
                      if (r.get("outcome_type") or "").strip().lower() == "binary"}

    w("## Table 2. Pooled placebo corrected percentage change from baseline, by biomarker")
    w("")
    w("| Biomarker | Hallmark domain | Trials | Change (%) | 95% CI | Prediction interval | I2 (%) | Direction |")
    w("|---|---|---:|---:|---|---|---:|---|")
    for r in sorted((x for x in t2 if x["biomarker"] not in binary_markers),
                    key=lambda x: (x["hallmark_domain"], x["biomarker"])):
        pi = "-" if r["pi_lo"] in ("", "NA") else f"{num(r['pi_lo'])} to {num(r['pi_hi'])}"
        ci = f"{num(r['lo'])} to {num(r['hi'])}"
        direction = "favourable" if (r.get("favourable") or "").strip().upper() == "TRUE" \
            else "UNFAVOURABLE"
        note = (r.get("note") or "").strip()
        w(f"| {r['biomarker']} | {r['hallmark_domain']} | {r['k']} | {num(r['est'])} | {ci} | {pi} | "
          f"{num(r['i2'], 0)} | {direction}{' (' + note + ')' if note else ''} |")
    w("")
    w("A positive value is an increase in the marker, not an improvement; the direction column")
    w("records whether the observed sign is the favourable one for that marker. Prediction intervals")
    w("are given where the between trial variance is estimable (three or more trials).")
    w("")

    # The binary outcomes, reported as counts because that is what they are.
    if binary_markers:
        w("### Binary hepatic histology outcomes, reported as counts and not pooled")
        w("")
        w("| Outcome | Trial | Duration (weeks) | Drug arm | Comparator arm |")
        w("|---|---|---:|---|---|")
        rows = [r for r in master if (r.get("biomarker") or "").strip() in binary_markers]
        for r in sorted(rows, key=lambda x: (x["biomarker"], x["trial_id"])):
            def frac(ev, n):
                try:
                    return f"{int(float(ev))} of {int(float(n))} ({100 * float(ev) / float(n):.1f}%)"
                except (TypeError, ValueError, ZeroDivisionError):
                    return "not reported"
            w(f"| {r['biomarker']} | {r['trial_id']} | {num(r.get('duration_weeks'), 0)} | "
              f"{frac(r.get('events_tx'), r.get('n_tx'))} | "
              f"{frac(r.get('events_ctrl'), r.get('n_ctrl'))} |")
        w("")
        w("These are not in Table 2, which holds pooled percentage changes only. One trial reports")
        w("MASH resolution and two report fibrosis improvement, and the two fibrosis trials point in")
        w("opposite directions at very different sizes, so a pooled fibrosis estimate is near zero")
        w("with an interval too wide to interpret. The counts show why, which the pooled row did")
        w("not.")
        w("")

    # ---- Table 3
    w("## Table 3. Receptor class coverage within placebo controlled trials (trials per class)")
    w("")
    classes = [c for c in ("GLP1_mono", "GLP1_GIP", "GLP1_GCGR", "GLP1_GIP_GCGR") if c in t3[0]]
    w("| Biomarker | " + " | ".join(c.replace("GLP1_", "") for c in classes) + " | Classes | Replicated |")
    w("|---|" + "---:|" * len(classes) + "---:|---|")
    for r in sorted(t3, key=lambda x: x["biomarker"]):
        vals = [int(r[c] or 0) for c in classes]
        repl = "yes" if sum(1 for v in vals if v >= 2) >= 2 else ""
        w(f"| {r['biomarker']} | " + " | ".join(str(v) for v in vals) +
          f" | {r['classes_present']} | {repl} |")
    w("")
    w("Replicated means at least two trials in each of at least two classes, the condition the")
    w("protocol sets for a class contrast that is not confounded with the identity of a single trial.")
    w("")

    # ---- Table 3b
    w("## Table 3b. Descriptive signature by class (NOT a contrast)")
    w("")
    w("| Receptor class | Markers | Domains | Mean signed change (%) |")
    w("|---|---:|---:|---:|")
    for r in t3b:
        w(f"| {r['receptor_class']} | {r['n_markers']} | {r['n_domains']} | {num(r['mean_signed'])} |")
    w("")
    w("Each class is summarised over a different marker set, so these means are not comparable to one")
    w("another and must never be presented as a class contrast.")
    w("")

    # ---- Table 4 (trial characteristics and risk of bias)
    trials = {}
    for r in master:
        t = trials.setdefault(r["trial_id"], dict(rows=0, drug=set(), cls=set(), comp=set(),
                                                  dur=set(), pop=set(), ind=set(), rob=set()))
        t["rows"] += 1
        t["drug"].add(r["drug"]); t["cls"].add(r["receptor_class"])
        t["comp"].add((r["comparator_type"] or "not recorded").lower())
        t["dur"].add(r["duration_weeks"]); t["pop"].add(r["population"])
        t["ind"].add(r["industry_funded"]); t["rob"].add(r["rob_overall"])
    w("## Table 4. Included trials, characteristics and risk of bias")
    w("")
    w("| Trial or analysis | Molecule | Receptor class | Comparator | Weeks | Population | Rows | RoB 2 |")
    w("|---|---|---|---|---:|---|---:|---|")
    for t in sorted(trials):
        d = trials[t]
        w(f"| {t} | {'; '.join(sorted(x for x in d['drug'] if x))} | {'; '.join(sorted(d['cls']))} | "
          f"{'; '.join(sorted(d['comp']))} | {sorted(d['dur'])[0]} | {'; '.join(sorted(d['pop']))} | "
          f"{d['rows']} | {'; '.join(sorted(x for x in d['rob'] if x))} |")
    w("")
    counts = collections.Counter(sorted(d["rob"])[0] for d in trials.values())
    w(f"Risk of bias over {len(trials)} contributing trials: " +
      ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ". " +
      f"Full domain level judgements for {len(rob)} trials are in analysis/data/risk_of_bias.csv.")
    w("")

    # ---- Table 5
    w("## Table 5. Net Biological Age Impact Score")
    w("")
    w("| Analysis | Markers | Score | 95% CI | Largest single share (%) | Dominant marker |")
    w("|---|---:|---:|---|---:|---|")
    for r in t5:
        w(f"| {r['analysis']} | {r['k']} | {num(r['score'])} | {num(r['lo'])} to {num(r['hi'])} | "
          f"{num(r['max_share'])} | {r['dominant']} |")
    w("")
    w("| Marker | Trials | Signed change (%) | Equal weight share (%) | Inverse variance share (%) |")
    w("|---|---:|---:|---:|---:|")
    for r in t5b:
        w(f"| {r['biomarker']} | {r['k']} | {num(r['signed'])} | {num(r['share_eq'])} | {num(r['share_iv'])} |")
    w("")

    # ---- Table 7
    w("## Table 7. Heterogeneity, prediction intervals and the imputed correlation sensitivity")
    w("")
    w("| Biomarker | Trials | I2 (%) | Prediction interval excludes no effect | Estimate at r 0.3 | r 0.5 | r 0.7 |")
    w("|---|---:|---:|---|---:|---:|---:|")
    by_bm = collections.defaultdict(dict)
    for r in sens:
        by_bm[r["biomarker"]][num(r["r"], 1)] = num(r["est"])
    def i2_key(x):
        try:
            return -float(x["i2"])
        except (TypeError, ValueError):
            return 1.0  # markers with one trial have no I2 and sort last
    for r in sorted(t2, key=i2_key):
        if r["pi_lo"] in ("", "NA"):
            excl = "not estimable"
        else:
            lo, hi = float(r["pi_lo"]), float(r["pi_hi"])
            excl = "yes" if lo * hi > 0 else "no"
        s = by_bm.get(r["biomarker"], {})
        w(f"| {r['biomarker']} | {r['k']} | {num(r['i2'], 0)} | {excl} | {s.get('0.3', '-')} | "
          f"{s.get('0.5', '-')} | {s.get('0.7', '-')} |")
    w("")
    w("The three right hand columns are the pooled estimate when the within patient correlation used")
    w("by the imputed change routes is set to 0.3, 0.5 and 0.7; a dash means no row of that marker")
    w("depends on an imputed correlation.")
    w("")
    w("## Table 6")
    w("")
    w("Table 6 (metabolic age normalisation thresholds) is drafted in the manuscript from")
    w("prespecification/q5_framework.md and is not regenerated here.")

    path = os.path.join(ROOT, "manuscript", f"TABLES_2_to_7_{stamp}.md")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(path, ROOT), f"({len(lines)} lines)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else date.today().isoformat())
